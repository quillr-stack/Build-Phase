async def seed_if_empty(kuzu_client):
    result = kuzu_client.query("MATCH (a:Agent) RETURN count(*)")
    count = 0
    if result.has_next():
        count = result.get_next()[0]

    if count == 0:
        # We need to map personas to agents for seeding
        # In this context, seeding the database with base personas as 'agents' for now
        agents_to_create = []
        for i, p in enumerate(SEED_PERSONAS):
            agent = {
                "agent_id": f"seed_agent_{i}",
                "persona_id": p["persona_id"],
                "segment": p["segment"],
                "state": p["state"],
                "trust_level": p["traits"]["trust_level"],
                "price_sensitivity": p["traits"]["price_sensitivity"],
                "digital_literacy": p["traits"]["digital_literacy"],
                "social_influence": p["traits"]["social_influence"],
                "religious_influence": p["traits"]["religious_influence"],
                "platform_preference": p["traits"]["platform_preference"]
            }
            agents_to_create.append(agent)

        await kuzu_client.create_agents(agents_to_create)
